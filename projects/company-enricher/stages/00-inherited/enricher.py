"""Company enricher.

Generated by an AI assistant. It works on the sample data.
"""
import re

from sample_web import SAMPLE_WEB

CATS = [
    "Retail",
    "Wholesale & Distribution",
    "Manufacturing",
    "Software & IT",
    "Healthcare",
    "Food & Hospitality",
    "Construction",
    "Finance",
    "Education",
    "Other",
]

KW = {
    "Retail": {"store", "shop", "sells", "retail", "boutique"},
    "Wholesale & Distribution": {"wholesale", "distribute", "distribution", "bulk", "warehouse"},
    "Manufacturing": {"manufacture", "manufacturing", "factory", "fabricate", "bake"},
    "Software & IT": {"software", "cloud", "technology", "apps", "hosting"},
    "Healthcare": {"clinic", "patients", "dental", "medical", "health"},
    "Food & Hospitality": {"restaurant", "cafe", "cafes", "catering", "breakfast", "lunch", "dinner", "bread", "pastries"},
    "Construction": {"build", "homes", "renovate", "construction", "builders"},
    "Finance": {"loans", "lending", "insurance", "banking", "accounting"},
    "Education": {"teach", "courses", "students", "exam", "school"},
    "Other": set(),
}


class M:
    def predict_proba(self, xs):
        r = []
        for x in xs:
            w = re.findall(r"[a-z]+", x.lower())
            s = [sum(1 for y in w if y in KW[c]) for c in CATS]
            n = sum(s)
            if n == 0:
                r.append([1 / len(CATS)] * len(CATS))
            else:
                r.append([v / n for v in s])
        return r


def run(xs, m, t=0.82):
    r = m.predict_proba(xs)
    return [
        x for x, p in zip(xs, r)
        if max(p) >= t
    ]


def go(n, db):
    d = SAMPLE_WEB.get(n)
    if not d:
        raise Exception("no site")
    x = d["about"].split(".")[0]
    p = M().predict_proba([x])[0]
    i = p.index(max(p))
    if max(p) < 0.82:
        return None
    db.append((n, CATS[i], max(p)))
    return CATS[i]


if __name__ == "__main__":
    db = []
    for n in SAMPLE_WEB:
        print(n, go(n, db))
